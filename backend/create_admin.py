MIN_PASSWORD_LENGTH = 12
REQUIRE_COMPLEXITY = True
MAX_FULL_NAME_LENGTH = 100
ALLOWED_NAME_CHARS = re.compile(r"^[a-zA-Z\s\-\'.]+$")

EMAIL_REGEX = re.compile(
    r"^[a-zA-Z0-9.!#$%&'*+/=?^_`{|}~-]+@"
    r"[a-zA-Z0-9-]+(?:\.[a-zA-Z0-9-]+)*$"
)


# ?????? Password input with visible masking ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def getpass_masked(prompt: str) -> str:
    """
    Read password and show * for each character typed.
    Works on Windows only (uses msvcrt).
    """
    print(prompt, end="", flush=True)
    password = []

    while True:
        ch = msvcrt.getch()

        if ch in (b"\r", b"\n"):  # Enter pressed
            print()  # New line
            break

        elif ch == b"\x08":  # Backspace
            if password:
                password.pop()
                # Erase character: backspace, space, backspace
                sys.stdout.write("\b \b")
                sys.stdout.flush()

        elif ch == b"\x03":  # Ctrl+C
            raise KeyboardInterrupt

        elif ch == b"\x00" or ch == b"\xe0":  # Special keys (arrows, F1-F12)
            msvcrt.getch()  # Consume the second byte
            continue

        else:
            try:
                char = ch.decode("utf-8")
                password.append(char)
                sys.stdout.write("*")
                sys.stdout.flush()
            except UnicodeDecodeError:
                continue

    return "".join(password)


# ?????? Validation helpers ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def validate_email(email: str) -> str:
    email = email.strip().lower()
    if not email or not EMAIL_REGEX.match(email):
        raise ValueError(f"Invalid email format: {email!r}")
    if len(email) > 254:
        raise ValueError("Email too long (max 254 characters).")
    return email


def validate_full_name(name: str) -> str:
    name = name.strip()
    if not name:
        raise ValueError("Full name cannot be empty.")
    if len(name) > MAX_FULL_NAME_LENGTH:
        raise ValueError(f"Full name too long (max {MAX_FULL_NAME_LENGTH} characters).")
    if not ALLOWED_NAME_CHARS.match(name):
        raise ValueError(
            "Full name contains invalid characters. "
            "Only letters, spaces, hyphens, apostrophes, and periods allowed."
        )
    name = re.sub(r"\s+", " ", name)
    return name


def check_password_strength(password: str) -> list:
    issues = []
    if len(password) < MIN_PASSWORD_LENGTH:
        issues.append(f"Must be at least {MIN_PASSWORD_LENGTH} characters.")
    if REQUIRE_COMPLEXITY:
        if not any(c.islower() for c in password):
            issues.append("Must contain at least one lowercase letter.")
        if not any(c.isupper() for c in password):
            issues.append("Must contain at least one uppercase letter.")
        if not any(c.isdigit() for c in password):
            issues.append("Must contain at least one digit.")
        if not any(c in string.punctuation for c in password):
            issues.append("Must contain at least one special character.")
    return issues


def generate_secure_password(length: int = 20) -> str:
    if length < MIN_PASSWORD_LENGTH:
        length = MIN_PASSWORD_LENGTH

    lowercase = string.ascii_lowercase
    uppercase = string.ascii_uppercase
    digits = string.digits
    special = "!@#$%^&*()-_=+[]{}|;:,.<>?"

    password_chars = [
        secrets.choice(lowercase),
        secrets.choice(uppercase),
        secrets.choice(digits),
        secrets.choice(special),
    ]
    all_chars = lowercase + uppercase + digits + special
    password_chars += [secrets.choice(all_chars) for _ in range(length - 4)]
    secrets.SystemRandom().shuffle(password_chars)
    return "".join(password_chars)


# ?????? Database helpers ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def admin_exists(db, email: str) -> bool:
    return db.scalar(select(User).where(User.email == email)) is not None


def create_admin_user(db, email: str, full_name: str, password: str) -> User:
    user = User(
        email=email,
        full_name=full_name,
        password_hash=hash_password(password),
        role="admin",
        is_active=True,
    )
    db.add(user)
    try:
        db.commit()
    except IntegrityError:
        db.rollback()
        raise ValueError(f"A user with email {email!r} already exists.")
    db.refresh(user)
    return user


# ?????? Main ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

def main() -> None:
    print("=" * 50)
    print("  Secure Admin Creation")
    print("=" * 50)
    print()

    # Email
    try:
        email = validate_email(input("Admin email: "))
    except ValueError as e:
        sys.exit(f"ERROR: {e}")

    # Full name
    try:
        full_name = validate_full_name(input("Full name: "))
    except ValueError as e:
        sys.exit(f"ERROR: {e}")

    # Password choice
    use_generated = (
        input("\nGenerate a secure password automatically? [Y/n]: ")
        .strip()
        .lower()
        in ("", "y", "yes")
    )

    if use_generated:
        password = generate_secure_password(length=20)
        generated = True
    else:
        password = None
        for attempt in range(3):
            typed = getpass_masked(
                f"Password (min {MIN_PASSWORD_LENGTH} chars, must include "
                f"upper, lower, digit, special): "
            )
            issues = check_password_strength(typed)
            if issues:
                print(f"\nWeak password:")
                for issue in issues:
                    print(f"  - {issue}")
                print(f"Attempts remaining: {2 - attempt}\n")
                continue
            confirm = getpass_masked("Repeat password: ")
            if confirm != typed:
                print(f"\nPasswords do not match. Attempts remaining: {2 - attempt}\n")
                continue
            password = typed
            generated = False
            break

        if password is None:
            sys.exit("ERROR: Too many failed attempts. Exiting.")

    # Database
    try:
        with SessionLocal() as db:
            if admin_exists(db, email):
                sys.exit(f"ERROR: A user with email {email!r} already exists.")
            user = create_admin_user(db, email, full_name, password)
            admin_id = user.id
    except ValueError as e:
        sys.exit(f"ERROR: {e}")
    except Exception as e:
        sys.exit(f"ERROR: Database error: {e}")

    # Success
    print()
    print("=" * 50)
    print(f"  Admin created successfully (ID: {admin_id})")
    print("=" * 50)
    print(f"  Email     : {email}")
    print(f"  Full Name : {full_name}")

    if generated:
        print()
        print("  GENERATED PASSWORD - shown only once. Save it now.")
        print(f"  Password  : {password}")
        print()
        print("  Store in a password manager. This will not be shown again.")
    else:
        print("  Password  : (as entered)")

    print()
    print("  Next steps:")
    print("  1. Log in to the dashboard with this email and password.")
    print("  2. Rotate this password after first login if shared.")
    print()


if __name__ == "__main__":
    main()
